# -*- coding: utf-8 -*-
"""Build the compact dataset consumed by the conversational evidence agent UI.

Inputs (generated by the analysis pipeline):
  outputs/tables/scenario_scores.csv
  outputs/tables/scenario_summary_final.csv
  outputs/tables/scenario_supply_final.csv
  outputs/tables/result2.csv
  outputs/tables/quality_card.json
  outputs/tables/result_meta.json

Output:
  outputs/agent_ui/data.json
  outputs/agent_ui/insights.json   (yearly trend + source mix, via agent_insights)
"""
from __future__ import annotations

import json
import math
import os
from datetime import datetime, timezone
from pathlib import Path

import pandas as pd

from agent_insights import build_insights, load_insights
from scenario_names import ROUTE_NAMES_EN, SCENARIO_NAMES_EN

BASE = Path(__file__).resolve().parents[1]
TAB = BASE / "outputs" / "tables"
OUT = BASE / "outputs" / "agent_ui"

SPAN_COLUMNS = [
    ("rule_demand_gate_evidence_span", "需求"),
    ("rule_business_gate_evidence_span", "业务"),
    ("rule_core_tech_gate_evidence_span", "AI能力"),
    ("rule_feasibility_gate_evidence_span", "实现路径"),
]


def _num(value, default=0.0):
    try:
        value = float(value)
    except (TypeError, ValueError):
        return default
    return default if math.isnan(value) else value


def _clean_text(value) -> str:
    text = str(value or "").replace("\n", " ").replace("\r", " ")
    while "  " in text:
        text = text.replace("  ", " ")
    return text.strip()


def _quote(row: pd.Series) -> tuple[str, list[str]]:
    parts, gates = [], []
    for column, label in SPAN_COLUMNS:
        span = _clean_text(row.get(column, ""))
        if span and span not in parts:
            parts.append(span)
            gates.append(label)
        if len(parts) >= 2:
            break
    quote = " / ".join(parts)
    if len(quote) > 240:
        quote = quote[:238] + "…"
    return quote, gates


def _evidence_for(df: pd.DataFrame, scenario: str, opp_limit: int = 4, extra_limit: int = 2):
    subset = df[df["scenario_final"] == scenario].copy()
    if subset.empty:
        return [], 0
    subset["_opp"] = subset["hybrid_is_opportunity"].fillna(0).astype(int)
    subset["_conf"] = subset["hybrid_overall_confidence"].astype(float).fillna(0.0)
    subset["_year"] = subset["year"].fillna(0).astype(int)
    subset = subset.sort_values(["_opp", "_conf"], ascending=[False, False])
    chosen, seen_titles = [], set()

    def take(row):
        quote, gates = _quote(row)
        if not quote:
            return False
        title = _clean_text(row.get("title", ""))
        key = title.lower()[:80]
        if key in seen_titles:
            return False
        seen_titles.add(key)
        chosen.append({
            "rid": str(row.get("uid") or row.get("rid") or ""),
            "title": title,
            "source": str(row.get("source", "")),
            "channel": str(row.get("channel", "")),
            "year": int(row.get("year") or 0),
            "url": str(row.get("url", "")),
            "confidence": round(float(row.get("hybrid_overall_confidence") or 0), 4),
            "is_opportunity": int(row.get("_opp") or 0),
            "gates": gates,
            "quote": quote,
            "snippet": _clean_text(row.get("text", ""))[:180],
        })
        return True

    opportunities = subset[subset["_opp"] == 1]
    for _, row in opportunities.iterrows():
        if len(chosen) >= opp_limit:
            break
        take(row)
    if len(chosen) < opp_limit + extra_limit:
        for _, row in subset[subset["_opp"] == 0].iterrows():
            if len(chosen) >= opp_limit + extra_limit:
                break
            take(row)
    return chosen, int((subset["_opp"] == 1).sum())


def build_insights_file(base: Path | None = None) -> dict:
    """Aggregate result2.csv into outputs/agent_ui/insights.json.

    Missing inputs degrade to an empty insights payload instead of failing the
    data build, so the chat UI keeps working without the trend/source charts.
    """
    base = Path(base or BASE)
    return build_insights(base / "outputs" / "tables" / "result2.csv",
                          base / "outputs" / "agent_ui" / "insights.json")


def build(base: Path | None = None) -> dict:
    base = Path(base or BASE)
    tab = base / "outputs" / "tables"
    scores = pd.read_csv(tab / "scenario_scores.csv")
    summary = pd.read_csv(tab / "scenario_summary_final.csv")
    supply = pd.read_csv(tab / "scenario_supply_final.csv")
    reviews = pd.read_csv(tab / "result2.csv")

    quality, run_meta = {}, {}
    if (tab / "quality_card.json").exists():
        quality = json.loads((tab / "quality_card.json").read_text(encoding="utf-8"))
    if (tab / "result_meta.json").exists():
        run_meta = json.loads((tab / "result_meta.json").read_text(encoding="utf-8"))

    summary_by_name = {str(r["scenario"]): r for _, r in summary.iterrows()}
    supply_by_name = {str(r["scenario"]): r for _, r in supply.iterrows()}

    scenarios = []
    for _, row in scores.sort_values("rank").iterrows():
        name = str(row["scenario"])
        srow = summary_by_name.get(name, {})
        sup = supply_by_name.get(name, {})
        evidence, opp_count = _evidence_for(reviews, name)
        scenarios.append({
            "name": name,
            "name_en": SCENARIO_NAMES_EN.get(name, name),
            "rank": int(row["rank"]),
            "n_docs": int(row["n_docs"]),
            "share": round(_num(row["share"]), 4),
            "demand": round(_num(row["demand"]), 4),
            "gap": round(_num(row["gap"]), 4),
            "feasibility": round(_num(row["feasibility"]), 4),
            "value": round(_num(row["value"]), 4),
            "opportunity": round(_num(row["opportunity"]), 4),
            "supply_maturity": round(_num(row["supply_maturity"]), 4),
            "mean_eng": round(_num(row["mean_eng"]), 4),
            "need_rate": round(_num(row["need_rate"]), 4),
            "wtp_rate": round(_num(row["wtp_rate"]), 4),
            "value_rate": round(_num(row["value_rate"]), 4),
            "urgency_rate": round(_num(srow.get("urgency_rate")), 4),
            "growth_slope": round(_num(row["growth_slope"]), 5),
            "source_entropy": round(_num(row["source_entropy"]), 4),
            "answer_rate": round(_num(row["answer_rate"]), 4),
            "repo_n": int(_num(row["repo_n"])),
            "repo_stars_sum": int(_num(row["repo_stars_sum"])),
            "paper_n": int(_num(row["paper_n"])),
            "show_n": int(_num(row["show_n"])),
            "product_n": int(_num(row["product_n"])),
            "barrier": round(_num(row["barrier"]), 4),
            "route": str(row["route"]),
            "route_en": ROUTE_NAMES_EN.get(str(row["route"]), str(row["route"])),
            "top_sources": str(srow.get("top_sources", "")),
            "opportunity_records": int(opp_count),
            "evidence": evidence,
        })

    top = scenarios[0]
    meta = {
        "title": "AI 应用场景机会雷达",
        "agent": "OpenECRS",
        "generated_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "records_raw": 52007,
        "records_clean": 45306,
        "units": 19621,
        "demand_units": 15525,
        "supply_units": 4096,
        "high_conf_samples": 2848,
        "evidence_records": int(run_meta.get("records") or len(reviews)),
        "evidence_opportunities": int(reviews["hybrid_is_opportunity"].fillna(0).astype(int).sum()),
        "evidence_mode": str(run_meta.get("mode", "rule")),
        "quality_state": str(quality.get("state", "needs_annotation")),
        "gold_records": int(quality.get("gold_records", 0) or 0),
        "calibration": "pending",
        "source_hhi": _num(quality.get("source_hhi"), 0.0),
        "span_evidence_rate": _num(quality.get("span_evidence_rate"), 0.0),
        "top_scenario": top["name"],
        "top_score": top["opportunity"],
        "weights": {"demand": 0.45, "gap": 0.25, "feasibility": 0.18, "value": 0.12},
        "data_cutoff": "2026-11-20",
    }
    data = {"meta": meta, "scenarios": scenarios}
    out = base / "outputs" / "agent_ui"
    out.mkdir(parents=True, exist_ok=True)
    (out / "data.json").write_text(json.dumps(data, ensure_ascii=False, indent=1), encoding="utf-8")
    build_insights_file(base)
    return data


if __name__ == "__main__":
    payload = build()
    insights = load_insights(BASE / "outputs" / "agent_ui" / "insights.json")
    insights_scenarios = insights.get("scenarios") or {}
    print(json.dumps({
        "scenarios": len(payload["scenarios"]),
        "evidence": sum(len(s["evidence"]) for s in payload["scenarios"]),
        "top": payload["meta"]["top_scenario"],
        "insights_scenarios": len(insights_scenarios),
        "insights_trend_points": sum(
            len((entry or {}).get("trend", {}).get("years", []))
            for entry in insights_scenarios.values()
        ),
        "output": "outputs/agent_ui/data.json",
        "insights_output": "outputs/agent_ui/insights.json",
    }, ensure_ascii=False, indent=2))
